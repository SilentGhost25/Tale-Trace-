def update_memory_and_pointer_map(cleaned_page_text: str, current_speaking_word_index: int = 0) -> Dict:
    """
    Merges cleaned page text into active memory using TaleTraceMemoryManager,
    reconciles pointers, and exports reading_state.py and pointer_map.json.
    """
    # 1. Update text via memory manager pipeline
    updated_memory = pipeline.process_ocr_text(cleaned_page_text)

    # 2. Build word pointer list
    words = build_word_pointer_map(updated_memory)
    pointer_map = {"words": words}

    # 3. Preserve the current speaking word index unless a page transition occurred
    word_idx = min(current_speaking_word_index, max(0, len(words) - 1)) if words else 0
    char_offset = words[word_idx]["start"] if words and word_idx < len(words) else 0

    # 4. Generate Python state code
    python_code = generate_python_code_state(
        book_title=settings.book_title,
        merged_text=updated_memory,
        word_map=words,
        current_word_idx=word_idx,
        current_char_offset=char_offset,
    )
    PYTHON_STATE_PATH.write_text(python_code, encoding="utf-8")

    # 5. Save JSON mirrors for backward compatibility
    MEMORY_PATH.write_text(json.dumps({"text": updated_memory}, ensure_ascii=False, indent=2), encoding="utf-8")
    POINTER_MAP_PATH.write_text(json.dumps(pointer_map, ensure_ascii=False, indent=2), encoding="utf-8")

    log.info(
        "Memory updated: %d total words. Reading state saved to %s",
        len(words),
        PYTHON_STATE_PATH.name,
    )
    # Display the exact content in terminal as requested
    display_merge_memory_terminal(updated_memory, current_word_idx=word_idx, total_words=len(words))
    return pointer_map


def get_memory_text() -> str:
    if MEMORY_PATH.exists():
        try:
            return json.loads(MEMORY_PATH.read_text(encoding="utf-8")).get("text", "")
        except Exception:
            pass
    return pipeline.merge_memory


def get_pointer_map() -> Dict:
    if POINTER_MAP_PATH.exists():
        try:
            return json.loads(POINTER_MAP_PATH.read_text(encoding="utf-8"))
        except Exception:
            pass
    return {"words": []}


def get_memory_text_up_to(word_index: int, include_prior_sessions: bool = True) -> str:
    """
    Returns all read text strictly up to and including word_index (no forward spoilers),
    joining prior session pages and the current page slice.
    """
    prior_slices: List[str] = []
    if include_prior_sessions and hasattr(pipeline, "permanent_memory"):
        for page in pipeline.permanent_memory:
            if page and page.strip():
                prior_slices.append(page.strip())

    current_page_text = get_memory_text().strip()
    current_slice = ""
    if current_page_text:
        words = build_word_pointer_map(current_page_text)
        if words and word_index >= 0:
            if word_index < len(words):
                end_char = words[word_index]["end"]
                current_slice = current_page_text[:end_char].strip()
            else:
                current_slice = current_page_text
        else:
            current_slice = current_page_text

    if current_slice:
        prior_slices.append(current_slice)

    return "\n\n".join(prior_slices).strip()


def recap_up_to(word_index: int, max_lines: int = 5, include_prior_sessions: bool = True) -> str:
    """
    Collects past read text strictly up to current word_index (no forward spoilers),
    optionally including archived pages from prior sessions, and returns a 4-5 line recap.
    """
    from ai_engine import generate_recap

    combined_text = get_memory_text_up_to(word_index, include_prior_sessions=include_prior_sessions)
    if not combined_text:
        return "No text has been read so far to recap."

    return generate_recap(combined_text, max_lines=max_lines)

