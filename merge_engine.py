"""
Merge Engine — runs continuously while both buttons are off (idle reading).

Responsibilities:
1. Clean OCR text: fix grammar/OCR noise against 'Septopus: Trouble on the High Cs'
   by Jyotin Goel, and strip running headers/footers/page numbers.
2. Maintain dynamic memory across frames and page transitions.
3. Generates Python state code (`reading_state.py`) and word pointer map so
   the offline TTS engine knows its exact word index across pause/resume.
"""
import json
import logging
from pathlib import Path
import re
from typing import Dict, List, Optional

from config import settings
from ocr_memory import pipeline, merge_ocr_with_groq

log = logging.getLogger("taletrace.merge")

MEMORY_PATH = Path("reading_memory.json")
POINTER_MAP_PATH = Path("pointer_map.json")
PYTHON_STATE_PATH = Path("reading_state.py")


def clean_ocr_text(raw_text: str) -> str:
    """Cleans OCR noise and strips headers/footers against the Septopus book."""
    if not raw_text or not raw_text.strip():
        return ""
    # Strip headers/footers locally without making redundant duplicate API calls
    return _strip_obvious_headers(raw_text)


def display_merge_memory_terminal(text: str, current_word_idx: int = 0, total_words: int = 0) -> None:
    """Prints clear, nicely formatted active merge memory content to the terminal."""
    border = "=" * 70
    sub_border = "-" * 70
    content = text.strip() if text and text.strip() else "[EMPTY / NO BOOK TEXT IN MEMORY]"
    
    print(f"\n{border}")
    print(f"📖 [ACTIVE MERGE MEMORY CONTENT] (Total Words: {total_words})")
    print(sub_border)
    print(content)
    print(sub_border)
    print(f"📍 Active Reading Pointer: Word #{current_word_idx}")
    print(f"{border}\n")


def _strip_obvious_headers(text: str) -> str:
    """Regex fallback to strip stray page numbers or uppercase running headers."""
    lines = text.splitlines()
    out = []
    for line in lines:
        stripped = line.strip()
        if re.fullmatch(r"\d{1,4}", stripped):
            continue  # standalone page number
        if len(stripped) <= 40 and stripped.isupper():
            continue  # uppercase running header
        out.append(line)
    return "\n".join(out).strip()


def build_word_pointer_map(text: str) -> List[Dict]:
    """Builds word-level character offset map: [{'w': word, 'start': int, 'end': int}]."""
    words = []
    for m in re.finditer(r"\S+", text):
        words.append({
            "w": m.group(0),
            "start": m.start(),
            "end": m.end(),
        })
    return words


